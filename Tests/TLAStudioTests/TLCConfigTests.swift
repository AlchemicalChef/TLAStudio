    // MARK: - ModelConfig Codable Tests

    func testModelConfigCodable() throws {
        let original = ModelConfig(
            name: "TestConfig",
            specFile: URL(fileURLWithPath: "/tmp/test.tla"),
            initPredicate: "MyInit",
            nextAction: "MyNext",
            constants: ["N": .int(3)],
            invariants: ["TypeOK"],
            workers: 8
        )

        let encoded = try JSONEncoder().encode(original)
        let decoded = try JSONDecoder().decode(ModelConfig.self, from: encoded)

        XCTAssertEqual(original.name, decoded.name)
        XCTAssertEqual(original.initPredicate, decoded.initPredicate)
        XCTAssertEqual(original.nextAction, decoded.nextAction)
        XCTAssertEqual(original.constants, decoded.constants)
        XCTAssertEqual(original.invariants, decoded.invariants)
        XCTAssertEqual(original.workers, decoded.workers)
    }

    // MARK: - Temp Config File Tests

    func testWriteTempConfigFile() throws {
        let config = ModelConfig(
            specFile: URL(fileURLWithPath: "/tmp/test.tla"),
            invariants: ["TypeOK"]
        )

        let url = try config.writeTempConfigFile()

        // Verify file exists
        XCTAssertTrue(FileManager.default.fileExists(atPath: url.path))

        // Verify content
        let content = try String(contentsOf: url, encoding: .utf8)
        XCTAssertTrue(content.contains("INVARIANT TypeOK"))

        // Clean up
        try? FileManager.default.removeItem(at: url)
    }

    // MARK: - ModelCheckProgress Tests

    func testModelCheckProgressPhases() {
        // Test all phase values
        let phases: [ModelCheckProgress.Phase] = [.parsing, .computing, .checkingLiveness, .done, .error]

        for phase in phases {
            let progress = ModelCheckProgress(sessionId: UUID(), phase: phase)
            XCTAssertEqual(progress.phase, phase)
        }
    }

    func testModelCheckProgressCodable() throws {
        let original = ModelCheckProgress(
            sessionId: UUID(),
            phase: .computing,
            statesFound: 1000,
            distinctStates: 500,
            statesLeft: 250,
            duration: 10.5,
            statesPerSecond: 100.0,
            currentAction: "Next",
            coverage: [ActionCoverage(actionName: "Init", count: 1, distinctStates: 1)],
            memoryUsed: 1024
        )

        let encoded = try JSONEncoder().encode(original)
        let decoded = try JSONDecoder().decode(ModelCheckProgress.self, from: encoded)

        XCTAssertEqual(original.sessionId, decoded.sessionId)
        XCTAssertEqual(original.phase, decoded.phase)
        XCTAssertEqual(original.statesFound, decoded.statesFound)
        XCTAssertEqual(original.distinctStates, decoded.distinctStates)
        XCTAssertEqual(original.statesPerSecond, decoded.statesPerSecond)
    }

    // MARK: - ActionCoverage Tests

    func testActionCoverageId() {
        let coverage = ActionCoverage(actionName: "Next", count: 100, distinctStates: 50)
        XCTAssertEqual(coverage.id, "Next")
    }

    func testActionCoverageCodable() throws {
        let original = ActionCoverage(actionName: "Next", count: 100, distinctStates: 50)
        let encoded = try JSONEncoder().encode(original)
        let decoded = try JSONDecoder().decode(ActionCoverage.self, from: encoded)

        XCTAssertEqual(original.actionName, decoded.actionName)
        XCTAssertEqual(original.count, decoded.count)
        XCTAssertEqual(original.distinctStates, decoded.distinctStates)
    }

    // MARK: - ModelCheckResult Tests

    func testModelCheckResultHasErrorTrace() {
        let resultWithTrace = ModelCheckResult(
            sessionId: UUID(),
            success: false,
            statesFound: 100,
            distinctStates: 50,
            duration: 1.0,
            coverage: [],
            errorTrace: ErrorTrace(type: .invariantViolation, message: "Test"),
            message: "Error"
        )

        XCTAssertTrue(resultWithTrace.hasErrorTrace)

        let resultWithoutTrace = ModelCheckResult(
            sessionId: UUID(),
            success: true,
            statesFound: 100,
            distinctStates: 50,
            duration: 1.0,
            coverage: [],
            errorTrace: nil,
            message: nil
        )

        XCTAssertFalse(resultWithoutTrace.hasErrorTrace)
    }

    func testModelCheckResultErrorTraceStateCount() {
        let trace = ErrorTrace(
            type: .invariantViolation,
            message: "Test",
            states: [
                TraceState(id: 0),
                TraceState(id: 1),
                TraceState(id: 2)
            ]
        )

        let result = ModelCheckResult(
            sessionId: UUID(),
            success: false,
            statesFound: 100,
            distinctStates: 50,
            duration: 1.0,
            coverage: [],
            errorTrace: trace,
            message: "Error"
        )

        XCTAssertEqual(result.errorTraceStateCount, 3)
    }

    func testModelCheckResultNoErrorTraceStateCount() {
        let result = ModelCheckResult(
            sessionId: UUID(),
            success: true,
            statesFound: 100,
            distinctStates: 50,
            duration: 1.0,
            coverage: [],
            errorTrace: nil,
            message: nil
        )

        XCTAssertEqual(result.errorTraceStateCount, 0)
    }
