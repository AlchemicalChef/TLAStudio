import XCTest
@testable import TLAStudioApp

// MARK: - TLC Config Tests

final class TLCConfigTests: XCTestCase {

    // MARK: - Default Values Tests

    func testDefaultModelConfig() {
        let config = ModelConfig(
            specFile: URL(fileURLWithPath: "/tmp/test.tla")
        )

        XCTAssertEqual(config.name, "Default")
        XCTAssertEqual(config.initPredicate, "Init")
        XCTAssertEqual(config.nextAction, "Next")
        XCTAssertTrue(config.constants.isEmpty)
        XCTAssertTrue(config.invariants.isEmpty)
        XCTAssertTrue(config.temporalProperties.isEmpty)
        XCTAssertNil(config.stateConstraint)
        XCTAssertNil(config.actionConstraint)
        XCTAssertEqual(config.workers, 4)
        XCTAssertTrue(config.checkDeadlock)
        XCTAssertFalse(config.depthFirst)
        XCTAssertNil(config.maxDepth)
        XCTAssertTrue(config.checkpointEnabled)
        XCTAssertEqual(config.checkpointInterval, 300)
    }

    // MARK: - Config File Generation Tests

    func testConfigFileGenerationBasic() {
        let config = ModelConfig(
            specFile: URL(fileURLWithPath: "/tmp/test.tla"),
            initPredicate: "Init",
            nextAction: "Next"
        )

        let content = config.generateConfigFile()

        XCTAssertTrue(content.contains("INIT Init"))
        XCTAssertTrue(content.contains("NEXT Next"))
        XCTAssertTrue(content.contains("Generated by TLA+ Studio"))
    }

    func testConfigFileGenerationWithCustomInitNext() {
        let config = ModelConfig(
            specFile: URL(fileURLWithPath: "/tmp/test.tla"),
            initPredicate: "MyInit",
            nextAction: "MyNext"
        )

        let content = config.generateConfigFile()

        XCTAssertTrue(content.contains("INIT MyInit"))
        XCTAssertTrue(content.contains("NEXT MyNext"))
    }

    func testConfigFileGenerationWithSpecificationPreservesSpecificationForm() {
        let config = ModelConfig(
            specFile: URL(fileURLWithPath: "/tmp/test.tla"),
            specification: "Spec",
            initPredicate: "Init",
            nextAction: "Next"
        )

        let content = config.generateConfigFile()

        XCTAssertTrue(content.contains("SPECIFICATION Spec"))
        XCTAssertFalse(content.contains("INIT Init"))
        XCTAssertFalse(content.contains("NEXT Next"))
    }

    func testParseConfigFilePreservesSpecificationDirective() {
        let parsed = ModelConfig.parse(content: """
        \\* Generated by TLA+ Studio
        SPECIFICATION Spec
        CONSTANT N = 3
        INVARIANT TypeOK
        """)

        XCTAssertEqual(parsed.specification, "Spec")
        XCTAssertEqual(parsed.constants["N"], .int(3))
        XCTAssertEqual(parsed.invariants, ["TypeOK"])
    }

    func testConfigFileGenerationWithConstants() {
        let config = ModelConfig(
            specFile: URL(fileURLWithPath: "/tmp/test.tla"),
            constants: [
                "N": .int(3),
                "Flag": .bool(true),
                "Name": .string("test")
            ]
        )

        let content = config.generateConfigFile()

        XCTAssertTrue(content.contains("CONSTANT N = 3"))
        XCTAssertTrue(content.contains("CONSTANT Flag = TRUE"))
        XCTAssertTrue(content.contains("CONSTANT Name = \"test\""))
    }

    func testConfigFileGenerationWithInvariants() {
        let config = ModelConfig(
            specFile: URL(fileURLWithPath: "/tmp/test.tla"),
            invariants: ["TypeOK", "Safety"]
        )

        let content = config.generateConfigFile()

        XCTAssertTrue(content.contains("INVARIANT TypeOK"))
        XCTAssertTrue(content.contains("INVARIANT Safety"))
    }

    func testConfigFileGenerationWithProperties() {
        let config = ModelConfig(
            specFile: URL(fileURLWithPath: "/tmp/test.tla"),
            temporalProperties: ["Liveness", "Fairness"]
        )

        let content = config.generateConfigFile()

        XCTAssertTrue(content.contains("PROPERTY Liveness"))
        XCTAssertTrue(content.contains("PROPERTY Fairness"))
    }

    func testConfigFileGenerationWithStateConstraint() {
        let config = ModelConfig(
            specFile: URL(fileURLWithPath: "/tmp/test.tla"),
            stateConstraint: "x < 10"
        )

        let content = config.generateConfigFile()

        XCTAssertTrue(content.contains("CONSTRAINT x < 10"))
    }

    func testConfigFileGenerationWithActionConstraint() {
        let config = ModelConfig(
            specFile: URL(fileURLWithPath: "/tmp/test.tla"),
            actionConstraint: "x' > x"
        )

        let content = config.generateConfigFile()

        XCTAssertTrue(content.contains("ACTION_CONSTRAINT x' > x"))
    }

    func testConfigFileGenerationWithSymmetry() {
        let config = ModelConfig(
            specFile: URL(fileURLWithPath: "/tmp/test.tla"),
            symmetrySets: ["Procs": ["p1", "p2", "p3"]]
        )

        let content = config.generateConfigFile()

        XCTAssertTrue(content.contains("SYMMETRY Procs"))
    }

    func testConfigFileGenerationEmptyConstraintsOmitted() {
        let config = ModelConfig(
            specFile: URL(fileURLWithPath: "/tmp/test.tla"),
            stateConstraint: "",  // Empty should be omitted
            actionConstraint: ""
        )

        let content = config.generateConfigFile()

        XCTAssertFalse(content.contains("CONSTRAINT"))
        XCTAssertFalse(content.contains("ACTION_CONSTRAINT"))
    }

    func testConfigFileGenerationEmptyInvariantsOmitted() {
        let config = ModelConfig(
            specFile: URL(fileURLWithPath: "/tmp/test.tla"),
            invariants: ["TypeOK", "", "Safety"]  // Empty should be filtered
        )

        let content = config.generateConfigFile()

        XCTAssertTrue(content.contains("INVARIANT TypeOK"))
        XCTAssertTrue(content.contains("INVARIANT Safety"))
        // Count INVARIANT occurrences - should be exactly 2
        let count = content.components(separatedBy: "INVARIANT").count - 1
        XCTAssertEqual(count, 2)
    }

